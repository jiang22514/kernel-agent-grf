function result=matlab_predict_delft(model_id,x_query)
%MATLAB_PREDICT_DELFT Exact saved-fit predictions; default is the 11 held-out CPTs.
[m,d]=matlab_load_delft(model_id);
if nargin<2,x_query=d.x_test;end
p=predict_gp_v2(m.kernel,m.mean_id,m,d.x,d.y_log,x_query);
v=p.latent_variance;vo=p.observation_variance;
result=struct('model_id',m.model_id,'x_query',x_query,'log_prediction',p, ...
    'median_qc_MPa',exp(p.mean),'latent_mean_qc_MPa',exp(p.mean+v/2), ...
    'latent_sd_qc_MPa',sqrt(expm1(v).*exp(2*p.mean+v)), ...
    'observation_mean_qc_MPa',exp(p.mean+vo/2), ...
    'observation_sd_qc_MPa',sqrt(expm1(vo).*exp(2*p.mean+vo)), ...
    'observation_interval90_MPa',exp(p.mean+[-1,1].*(1.6448536269514722*sqrt(vo))));
end
